"""Markdown for the docs PR body and for the "already in sync" comment."""

from dataclasses import dataclass

from driftless.pipeline import AnalysisResult
from driftless.proposals import DocProposals, Verification, VerificationStatus

BANNER = "🤖 Generated by Driftless"
FOOTER = "<sub>Generated by Driftless</sub>"


def source_marker(number: int) -> str:
    """Hidden marker identifying Driftless's PRs and comments for a source PR."""
    return f"<!-- driftless:source-pr={number} -->"


def has_source_marker(body: str, number: int) -> bool:
    """Also matches comments posted before the rename, so reruns edit them instead of adding one."""
    return source_marker(number) in body or f"<!-- docdrift:source-pr={number} -->" in body


@dataclass(frozen=True)
class ChangeRow:
    file: str
    section: str
    change: str  # "updated" | "added"
    why: str
    confidence: float
    verification: Verification
    matched_terms: tuple[str, ...] = ()

    @property
    def applied(self) -> bool:
        return self.verification.applied


def change_rows(proposals: DocProposals, min_confidence: float) -> list[ChangeRow]:
    """Every change Driftless tried to make: confident and verified, fixed, or dropped."""
    rows: list[ChangeRow] = []
    for f in proposals.findings:
        v = f.verdict
        if v.stale and v.confidence >= min_confidence and f.verification is not None:
            # Drop the document title (the file column already says which document).
            path = f.section.heading_path
            section = " › ".join(path[1:] if len(path) > 1 else path) or f.section.heading
            rows.append(
                ChangeRow(f.section.path, section, "updated", v.reason, v.confidence, f.verification, tuple(f.matched_terms))
            )
    for ins in proposals.insertions:
        p = ins.proposal
        if p.confidence >= min_confidence and ins.verification is not None:
            heading = p.section.strip().splitlines()[0].lstrip("#").strip()
            where = f"{heading} (after {p.after_heading})" if p.after_heading else f"{heading} (end of file)"
            rows.append(ChangeRow(p.file, where, "added", p.reason, p.confidence, ins.verification, (ins.item.name,)))
    return rows


def render_pr_body(
    result: AnalysisResult,
    proposals: DocProposals,
    min_confidence: float,
    changed_files: list[str],
    skipped_files: list[str] | None = None,
) -> str:
    pr = result.pr
    rows = change_rows(proposals, min_confidence)
    applied = [r for r in rows if r.applied and r.file in changed_files]
    dropped = [r for r in rows if not r.applied]
    updated = sum(1 for r in applied if r.change == "updated")
    added = sum(1 for r in applied if r.change == "added")

    parts = [
        source_marker(pr.number),
        BANNER,
        "",
        f"Syncs the documentation with [{pr.repo}#{pr.number}]({pr.url}): **{_cell(pr.title)}**.",
        "",
        f"{_summary(updated, added, len(changed_files))}",
        "",
        "| File | Section | Change | Why | Confidence | Verification |",
        "|------|---------|--------|-----|-----------:|--------------|",
    ]
    parts += [
        f"| `{r.file}` | {_cell(r.section)} | {r.change} | {_cell(_first_sentence(r.why))} "
        f"| {r.confidence:.2f} | {_cell(status_label(r.verification))} |"
        for r in rows
    ]
    for covered in proposals.covered:
        parts.append(
            f"| `{covered.file}` | {_cell(covered.item.name)} | covered | documented by a section update above | | |"
        )
    if dropped:
        parts += ["", "### Dropped changes", ""]
        parts += [f"- `{r.file}` › {r.section}: {_dropped_reason(r.verification)}" for r in dropped]
    if skipped_files:
        parts += ["", "### Not applied", ""]
        parts += [
            f"- `{path}` changed on the default branch since #{pr.number} was merged; rerun Driftless to update it."
            for path in skipped_files
        ]
    parts += ["", "<details>", "<summary>Model reasoning per change</summary>", ""]
    for r in rows:
        parts += _reasoning(r)
    parts += ["</details>", "", "---", FOOTER, ""]
    return "\n".join(parts)


def render_sync_comment(
    result: AnalysisResult, proposals: DocProposals, min_confidence: float, skipped_files: list[str] | None = None
) -> str:
    """Comment for the source PR when Driftless has nothing to commit."""
    rows = change_rows(proposals, min_confidence)
    docs = len(result.docs)
    header = source_marker(result.pr.number)
    if skipped_files:
        files = ", ".join(f"`{p}`" for p in skipped_files)
        return (
            f"{header}\n⚠️ **Driftless** prepared updates for {files}, but they changed on the default branch "
            f"since #{result.pr.number} was merged, so nothing was committed. Rerun Driftless to sync them."
            "\n\n---\n" + FOOTER + "\n"
        )
    if not rows:
        return (
            f"{header}\n✅ **Driftless:** the docs are already in sync with this PR. "
            f"Checked {len(result.candidates)} related section(s) across {docs} doc file(s); "
            "nothing is stale and no new interface is undocumented.\n\n---\n" + FOOTER + "\n"
        )
    lines = [
        header,
        "⚠️ **Driftless** found doc sections that may be stale, but none of its proposed changes passed "
        "verification against the code, so no docs PR was opened:",
        "",
    ]
    lines += [f"- `{r.file}` › {r.section}: {_dropped_reason(r.verification)}" for r in rows]
    return "\n".join(lines + ["", "---", FOOTER, ""])


def status_label(verification: Verification) -> str:
    if verification.status == VerificationStatus.VERIFIED:
        return "✅ verified"
    if verification.status == VerificationStatus.FIXED_ON_RETRY:
        return "🔁 fixed on retry"
    return f"⚠️ dropped: {_dropped_reason(verification)}"


def _summary(updated: int, added: int, files: int) -> str:
    return f"Updated {_plural(updated, 'section')}, added {_plural(added, 'section')} across {_plural(files, 'file')}."


def _plural(n: int, noun: str) -> str:
    return f"{n} {noun}" if n == 1 else f"{n} {noun}s"


def _dropped_reason(verification: Verification) -> str:
    reasons = verification.retry_failures or verification.failures
    if reasons:
        return "; ".join(reasons)
    return verification.note or "failed verification"


def _reasoning(row: ChangeRow) -> list[str]:
    lines = [f"**`{row.file}` › {row.section}** ({row.change}, confidence {row.confidence:.2f})", ""]
    lines += [f"> {line}" if line else ">" for line in row.why.strip().splitlines()]
    lines.append("")
    v = row.verification
    if row.matched_terms:
        lines.append("- Triggered by: " + ", ".join(f"`{t}`" for t in row.matched_terms))
    if v.failures and v.status != VerificationStatus.DROPPED:
        lines.append("- First draft failed verification: " + "; ".join(v.failures))
    if v.status == VerificationStatus.DROPPED:
        lines.append(f"- Dropped: {_dropped_reason(v)}")
    if v.restored_lines:
        lines.append(f"- Restored {v.restored_lines} cosmetically changed line(s) to the original text")
    lines += [f"- Review flag: {flag}" for flag in v.flags]
    return lines + [""]


def _first_sentence(text: str) -> str:
    text = " ".join(text.split())
    end = text.find(". ")
    return text if end == -1 else text[: end + 1]


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")
