"""Markdown for the docs PR body and for the "already in sync" comment."""

from dataclasses import dataclass

from driftless.doc_index import is_doc_path
from driftless.example_impact import example_impact, impact_sentence
from driftless.execution import ExampleOutcome, ExampleStatus, ExecutionReport
from driftless.pipeline import AnalysisResult
from driftless.proposals import DocProposals, Verification, VerificationStatus

BANNER = "🤖 Generated by Driftless"
FOOTER = "<sub>Generated by Driftless</sub>"


def source_marker(number: int) -> str:
    """Hidden marker identifying Driftless's PRs and comments for a source PR."""
    return f"<!-- driftless:source-pr={number} -->"


def has_source_marker(body: str, number: int) -> bool:
    """Also matches comments posted before the rename, so reruns edit them instead of adding one."""
    return source_marker(number) in body or f"<!-- docdrift:source-pr={number} -->" in body


@dataclass(frozen=True)
class ChangeRow:
    file: str
    section: str
    change: str  # "updated" | "added"
    why: str
    confidence: float
    verification: Verification
    matched_terms: tuple[str, ...] = ()
    pre_existing: bool = False

    @property
    def applied(self) -> bool:
        return self.verification.applied


def change_rows(proposals: DocProposals, min_confidence: float) -> list[ChangeRow]:
    """Every change Driftless tried to make: confident and verified, fixed, or dropped."""
    rows: list[ChangeRow] = []
    for f in proposals.findings:
        v = f.verdict
        if v.stale and v.confidence >= min_confidence and f.verification is not None:
            # Drop the document title (the file column already says which document).
            path = f.section.heading_path
            section = " › ".join(path[1:] if len(path) > 1 else path) or f.section.heading
            rows.append(
                ChangeRow(
                    f.section.path, section, "updated", v.reason, v.confidence, f.verification,
                    tuple(f.matched_terms), f.pre_existing,
                )
            )
    for ins in proposals.insertions:
        p = ins.proposal
        if p.confidence >= min_confidence and ins.verification is not None:
            heading = p.section.strip().splitlines()[0].lstrip("#").strip()
            where = f"{heading} (after {p.after_heading})" if p.after_heading else f"{heading} (end of file)"
            rows.append(ChangeRow(p.file, where, "added", p.reason, p.confidence, ins.verification, (ins.item.name,)))
    return rows


def render_pr_body(
    result: AnalysisResult,
    proposals: DocProposals,
    min_confidence: float,
    changed_files: list[str],
    skipped_files: list[str] | None = None,
) -> str:
    pr = result.pr
    rows = change_rows(proposals, min_confidence)
    applied = [r for r in rows if r.applied and r.file in changed_files]
    dropped = [r for r in rows if not r.applied]
    updated = sum(1 for r in applied if r.change == "updated")
    added = sum(1 for r in applied if r.change == "added")
    execution = proposals.execution
    fixed = len(execution.fixed) if execution else 0

    parts = [
        source_marker(pr.number),
        BANNER,
        "",
        f"Syncs the documentation with [{pr.repo}#{pr.number}]({pr.url}): **{_cell(pr.title)}**.",
        "",
        f"{_summary(updated, added, fixed, len(changed_files))}",
        "",
    ]
    impact = example_impact(execution.outcomes) if execution else None
    if impact and impact.roots:
        parts += [impact_sentence(impact, f"#{pr.number}"), ""]
    if not rows and not proposals.covered:
        parts.append(
            "Static analysis found no stale sections. Every change below comes from running the docs' "
            "examples against the app at the merge commit."
        )
    else:
        parts += [
            "| File | Section | Change | Why | Confidence | Verification |",
            "|------|---------|--------|-----|-----------:|--------------|",
        ]
    parts += [
        f"| `{r.file}` | {_cell(r.section)} | {r.change} | {_cell(_first_sentence(r.why))} "
        f"| {r.confidence:.2f} | {_cell(status_label(r.verification))} |"
        for r in rows
    ]
    for covered in proposals.covered:
        parts.append(
            f"| `{covered.file}` | {_cell(covered.item.name)} | covered | documented by a section update above | | |"
        )
    if execution:
        parts += ["", *render_execution(execution)]
    if dropped:
        parts += ["", "### Dropped changes", ""]
        parts += [f"- `{r.file}` › {r.section}: {_dropped_reason(r.verification)}" for r in dropped]
    if skipped_files:
        parts += ["", "### Not applied", ""]
        parts += [
            f"- `{path}` changed on the default branch since #{pr.number} was merged; rerun Driftless to update it."
            for path in skipped_files
        ]
    if rows:
        parts += ["", "<details>", "<summary>Model reasoning per change</summary>", ""]
        for r in rows:
            parts += _reasoning(r)
        parts.append("</details>")
    parts += ["", "---", FOOTER, ""]
    return "\n".join(parts)


def render_sync_comment(
    result: AnalysisResult, proposals: DocProposals, min_confidence: float, skipped_files: list[str] | None = None
) -> str:
    """Comment for the source PR when Driftless has nothing to commit."""
    rows = change_rows(proposals, min_confidence)
    header = source_marker(result.pr.number)
    if skipped_files:
        files = ", ".join(f"`{p}`" for p in skipped_files)
        return (
            f"{header}\n⚠️ **Driftless** prepared updates for {files}, but they changed on the default branch "
            f"since #{result.pr.number} was merged, so nothing was committed. Rerun Driftless to sync them."
            "\n\n---\n" + FOOTER + "\n"
        )
    execution = proposals.execution
    if not rows and execution and execution.failing:
        roots = [o for o in execution.failing if o.root_cause]
        lines = [
            header,
            f"❌ **Driftless:** {_plural(len(roots), 'documented example')} failed against the app "
            "and could not be fixed automatically, so no docs PR was opened. Please update them:",
            "",
        ]
        lines += [
            f"- `{o.file}` › `{o.label}` (line {o.line}): {_cell('; '.join(o.failures))}"
            + (f" ({_cell(o.note)})" if o.blocked_by and o.note else "")
            for o in execution.failing
        ]
        return "\n".join(lines + ["", "---", FOOTER, ""])
    if not rows:
        ran = ""
        if execution and execution.total:
            ran = f" {_all_pass(execution.total)} against the app."
        if any(is_doc_path(f.path) for f in result.pr.files):
            ran += " The docs were updated in this PR before it was merged."
        return (
            f"{header}\n✅ **Driftless:** the docs are already in sync with this PR. "
            f"{checked_sentence(result, execution)}; "
            f"nothing is stale and no new interface is undocumented.{ran}\n\n---\n" + FOOTER + "\n"
        )
    lines = [
        header,
        "⚠️ **Driftless** found doc sections that may be stale, but none of its proposed changes passed "
        "verification against the code, so no docs PR was opened:",
        "",
    ]
    lines += [f"- `{r.file}` › {r.section}: {_dropped_reason(r.verification)}" for r in rows]
    return "\n".join(lines + ["", "---", FOOTER, ""])


EXAMPLE_LABELS = {
    ExampleStatus.PASSED: "🧪 passed",
    ExampleStatus.FIXED: "🔁 fixed after running",
    ExampleStatus.FAILING: "❌ still failing",
    ExampleStatus.DEPENDENT: "⛓️ failed only because of an earlier example",
}


def checked_sentence(result: AnalysisResult, execution: ExecutionReport | None) -> str:
    """What Driftless actually looked at: 'Checked 14 doc sections (3 reviewed by the model) and
    ran 6 examples across 2 doc files'."""
    sections = _plural(len(result.sections), "doc section")
    if result.candidates:
        sections += f" ({len(result.candidates)} reviewed by the model)"
    ran = f" and ran {_plural(execution.total, 'example')}" if execution and execution.total else ""
    return f"Checked {sections}{ran} across {_plural(len(result.docs), 'doc file')}"


def _all_pass(n: int) -> str:
    return "The 1 documented example passes" if n == 1 else f"All {n} documented examples pass"


def render_execution(report: ExecutionReport) -> list[str]:
    """The "🧪 Executed examples" section: every example run against the real app."""
    app = f" against `{report.app}`" if report.app else ""
    parts = [
        f"### 🧪 Executed examples: {report.passing}/{report.total} passing",
        "",
        f"Every request example in the docs was run{app}, started from this commit "
        "(a fresh app per file, examples in document order).",
        "",
    ]
    if report.outcomes:
        parts += [
            "| File | Example | Expected status | Actual status | Result |",
            "|------|---------|----------------:|--------------:|--------|",
        ]
        parts += [
            f"| `{o.file}` | `{_cell(o.label)}` (line {o.line}) | {_expected_status(o)} "
            f"| {_status(o.final_actual_status)} | {_example_result(o)}{' (pre-existing)' if o.pre_existing else ''} |"
            for o in report.outcomes
        ]
    if report.fixed:
        parts += ["", "**Fixed after running**", ""]
        parts += [
            f"- `{o.file}` › `{o.label}`: {_cell('; '.join(o.fixes))} (was: {_cell('; '.join(o.failures))})"
            for o in report.fixed
        ]
    failing = [o for o in report.failing if not o.pre_existing]  # pre-existing ones are listed separately
    if failing:
        parts += ["", "**❌ Still failing — please review before merging**", ""]
        parts += [
            f"- `{o.file}` › `{o.label}` (line {o.line}): {_cell('; '.join(o.failures))}"
            + (f" ({_cell(o.note)})" if o.note else "")
            for o in failing
        ]
    if report.dependent:
        n = len(report.dependent)
        parts += [
            "",
            "<details>",
            f"<summary>⛓️ {_plural(n, 'later example')} failed only because of an earlier one "
            f"({'it passes' if n == 1 else 'they pass'} once that one is fixed)</summary>",
            "",
        ]
        parts += [
            f"- `{o.file}` › `{o.label}` (line {o.line}): failed only because of {_cell(o.caused_by or 'an earlier example')}"
            f" (was: {_cell('; '.join(o.failures))})"
            for o in report.dependent
        ]
        parts += ["", "</details>"]
    warned = [o for o in report.outcomes if o.warnings]
    if warned:
        parts += ["", "<details>", "<summary>Value differences (warnings, not failures)</summary>", ""]
        parts += [f"- `{o.file}` › `{o.label}`: {_cell('; '.join(o.warnings))}" for o in warned]
        parts += ["", "</details>"]
    if report.errors:
        parts += ["", *[f"- ⚠️ {_cell(error)}" for error in report.errors]]
    return parts


def render_check_body(repo: str, ref: str, report: ExecutionReport, changed_files: list[str]) -> str:
    """Body of the PR opened by `driftless check --fix`."""
    files = ", ".join(f"`{p}`" for p in changed_files)
    parts = [
        BANNER,
        "",
        f"Docs health audit of `{repo}` at `{ref}`: Driftless ran every request example in the docs "
        f"against the real app and fixed the ones that didn't work, in {files}.",
        "",
        *render_execution(report),
        "",
        "---",
        FOOTER,
        "",
    ]
    return "\n".join(parts)


def _example_result(outcome: ExampleOutcome) -> str:
    if outcome.status == ExampleStatus.DEPENDENT and outcome.caused_by:
        return f"⛓️ failed only because of {_cell(outcome.caused_by)}"
    return EXAMPLE_LABELS[outcome.status]


def _expected_status(outcome: ExampleOutcome) -> str:
    final = _status(outcome.final_expected_status)
    if outcome.expected_status != outcome.final_expected_status:
        return f"~~{_status(outcome.expected_status)}~~ {final}"
    return final


def _status(code: int | None) -> str:
    return str(code) if code is not None else "—"


def status_label(verification: Verification) -> str:
    if verification.status == VerificationStatus.VERIFIED:
        return "✅ verified"
    if verification.status == VerificationStatus.FIXED_ON_RETRY:
        return "🔁 fixed on retry"
    return f"⚠️ dropped: {_dropped_reason(verification)}"


def _summary(updated: int, added: int, fixed_examples: int, files: int) -> str:
    fixed = f", fixed {_plural(fixed_examples, 'example')} after running" if fixed_examples else ""
    return (
        f"Updated {_plural(updated, 'section')}, added {_plural(added, 'section')}{fixed} "
        f"across {_plural(files, 'file')}."
    )


def _plural(n: int, noun: str) -> str:
    return f"{n} {noun}" if n == 1 else f"{n} {noun}s"


def _dropped_reason(verification: Verification) -> str:
    reasons = verification.retry_failures or verification.failures
    if reasons:
        return "; ".join(reasons)
    return verification.note or "failed verification"


def _reasoning(row: ChangeRow) -> list[str]:
    lines = [f"**`{row.file}` › {row.section}** ({row.change}, confidence {row.confidence:.2f})", ""]
    lines += [f"> {line}" if line else ">" for line in row.why.strip().splitlines()]
    lines.append("")
    v = row.verification
    if row.matched_terms:
        lines.append("- Triggered by: " + ", ".join(f"`{t}`" for t in row.matched_terms))
    if v.failures and v.status != VerificationStatus.DROPPED:
        lines.append("- First draft failed verification: " + "; ".join(v.failures))
    if v.status == VerificationStatus.DROPPED:
        lines.append(f"- Dropped: {_dropped_reason(v)}")
    if v.restored_lines:
        lines.append(f"- Restored {v.restored_lines} cosmetically changed line(s) to the original text")
    lines += [f"- Review flag: {flag}" for flag in v.flags]
    return lines + [""]


def _first_sentence(text: str) -> str:
    text = " ".join(text.split())
    end = text.find(". ")
    return text if end == -1 else text[: end + 1]


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")
